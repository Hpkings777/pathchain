// PATHchain — Markets: simulated PATH/USD chart + real-coin market list.
import { App, api } from '../api.js';
import { ensureEngine, onTick, onCoins, pathSeries, pathSnapshot, activityInputs, updateChainStats, coins as coinState } from '../market.js';
import { fmtUsd, fmtPct, fmtCompact, fmtNum } from '../fmt.js';
import { esc, empty, badge, tweenNumber, flashNum } from '../ui.js';
import { priceChart, spark } from '../spark.js';

const WINDOWS = [
  { id: '1H', sec: 3600 },
  { id: '24H', sec: 86400 },
  { id: '7D', sec: 604800 },
  { id: 'ALL', sec: 5600800 },
];

let tf = '24H';
let offTick = null, offCoins = null, offLive = null;
let lastPaintKey = '';
let prevPrice = null;

export async function render(container) {
  ensureEngine();
  container.innerHTML = `
    <div class="section-head"><h2>Markets</h2>
      <span class="right muted">PATH pricing is simulated — real coins use public market data</span></div>

    <div class="mkt-grid">
      <div class="card mkt-hero">
        <div class="mkt-hero-top">
          <div class="mkt-coin-id">
            <span class="coin-badge path">P</span>
            <div>
              <div class="mkt-name">PATH <span class="muted">/ USD</span></div>
              <div class="mkt-sub">PATHchain native currency · <span class="tag-sys">SIMULATED MARKET</span></div>
            </div>
          </div>
          <div class="mkt-price-box">
            <div class="mkt-price" id="mkt-price">—</div>
            <div class="mkt-chg-row">
              <span class="chg-chip" id="mkt-chg">—</span>
              <span class="muted small-text" id="mkt-act" title="Multiplier applied by live network activity"></span>
            </div>
          </div>
        </div>
        <div class="tf-tabs" id="tf-tabs" role="tablist">
          ${WINDOWS.map(w => `<button role="tab" data-tf="${w.id}" class="${w.id === tf ? 'active' : ''}">${w.id}</button>`).join('')}
        </div>
        <div class="mkt-chart-host"><canvas id="mkt-chart"></canvas></div>
        <div class="mkt-stat-row" id="mkt-stats"></div>
      </div>

      <div class="card mkt-how">
        <h3>How this price is made</h3>
        <p class="muted small-text">PATH has no real-world value — its chart is generated by a transparent engine,
          so every device on the network sees the same series:</p>
        <ol class="mkt-how-list">
          <li><b>Deterministic random walk</b> — a hash chain produces the same volatility history everywhere (regimes + occasional pump/dump events).</li>
          <li><b>Adoption trend</b> — slow upward drift, like a growing network.</li>
          <li><b>Live activity factor</b> — multiplies the price using your chain's real numbers:</li>
        </ol>
        <div id="mkt-inputs" class="mkt-inputs">${empty('Waiting for chain state…')}</div>
        <p class="muted small-text">Mine a block or send a transfer, then watch this factor — and the price — move.</p>
      </div>
    </div>

    <div class="section-head"><h2>All markets</h2>
      <span class="right" id="coins-state"></span></div>
    <div class="card">
      <div class="mkt-list" id="mkt-list">
        <div class="mkt-row mkt-head-row">
          <span class="mc-asset">Asset</span><span class="mc-price">Price</span>
          <span class="mc-chg">24h</span><span class="mc-spark">Last 7 days</span><span class="mc-mcap">Market cap</span>
        </div>
        <div id="mkt-rows"><div class="empty">Loading market data…</div></div>
      </div>
    </div>`;

  container.querySelectorAll('#tf-tabs button').forEach(b => {
    b.onclick = () => {
      tf = b.dataset.tf;
      container.querySelectorAll('#tf-tabs button').forEach(x => x.classList.toggle('active', x === b));
      lastPaintKey = '';
      paintChart(pathSnapshot());
    };
  });

  const paint = (snap) => {
    updateChainStats(App.state ? App.state.stats : null);
    const s = snap || pathSnapshot();
    const priceEl = document.getElementById('mkt-price');
    if (!priceEl) return; // page torn down
    // count up/down to the new price with a green/red beat — the exchange feel
    tweenNumber(priceEl, s.price, fmtUsd);
    if (prevPrice !== null && Math.abs(s.price - prevPrice) > 1e-9) {
      priceEl.classList.remove('flash-up', 'flash-down');
      void priceEl.offsetWidth;
      priceEl.classList.add(s.price > prevPrice ? 'flash-up' : 'flash-down');
    }
    prevPrice = s.price;
    const chg = document.getElementById('mkt-chg');
    chg.textContent = `${fmtPct(s.chg24h)} (24h)`;
    chg.className = 'chg-chip ' + (s.chg24h >= 0 ? 'up' : 'down');
    const act = document.getElementById('mkt-act');
    act.textContent = `activity ×${s.act.toFixed(3)}`;
    paintStats(s);
    paintChart(s);
    paintInputs();
  };

  const paintCoins = () => {
    const stateEl = document.getElementById('coins-state');
    const rows = document.getElementById('mkt-rows');
    if (!rows) return;
    if (stateEl) {
      if (coinState.state === 'live') stateEl.innerHTML = '<span class="green">live via public API</span>';
      else if (coinState.state === 'cached') stateEl.innerHTML = `<span class="yellow">offline — showing last fetched prices</span>`;
      else if (coinState.state === 'offline') stateEl.innerHTML = `<span class="yellow">offline — real-coin prices unavailable</span>`;
      else stateEl.textContent = '';
    }
    const pathRow = pathRowHtml();
    const coinRows = coinState.rows.map(coinRowHtml).join('');
    rows.innerHTML = pathRow + (coinRows ||
      `<div class="empty">BTC, ETH and other real coins appear here when this device can reach the public price API.</div>`);
    // paint sparklines after DOM insert
    const pathCv = rows.querySelector('.mkt-row.featured canvas');
    if (pathCv) {
      const p7 = pathSeries(604800, 84).map(p => p.v);
      if (p7.length > 1) spark(pathCv, p7, { color: '#7ca5cc', height: 34 });
    }
    coinState.rows.forEach(c => {
      const cv = rows.querySelector(`canvas[data-spark="${c.id}"]`);
      if (cv && c.spark.length > 1) {
        spark(cv, c.spark, { color: c.chg24h >= 0 ? 'var(--green)' : 'var(--red)', height: 34 });
      }
    });
  };

  paintInputs();
  paint(pathSnapshot());
  paintCoins();
  offTick = onTick(paint);
  offCoins = onCoins(paintCoins);
  offLive = App.on((s) => { if (s) updateChainStats(s.stats); });
}

function paintStats(s) {
  const box = document.getElementById('mkt-stats');
  if (!box) return;
  box.innerHTML = `
    <div><div class="mkt-stat-k">24h high</div><div class="mkt-stat-v">${fmtUsd(s.high24)}</div></div>
    <div><div class="mkt-stat-k">24h low</div><div class="mkt-stat-v">${fmtUsd(s.low24)}</div></div>
    <div><div class="mkt-stat-k">24h volume</div><div class="mkt-stat-v">${fmtCompact(s.volume24)} <span class="tag-sys">SIM</span></div></div>
    <div><div class="mkt-stat-k">Market cap</div><div class="mkt-stat-v">${fmtCompact(s.mcap)}</div></div>
    <div><div class="mkt-stat-k">Circulating supply</div><div class="mkt-stat-v">${fmtNum(s.supply)} PATH</div></div>
    <div><div class="mkt-stat-k">7d change</div><div class="mkt-stat-v ${s.chg7d >= 0 ? 'green' : 'red'}">${fmtPct(s.chg7d)}</div></div>`;
}

function paintChart(s) {
  const win = WINDOWS.find(w => w.id === tf) || WINDOWS[1];
  const pts = pathSeries(win.sec).map(p => ({ t: p.t, v: p.v }));
  const cv = document.getElementById('mkt-chart');
  if (!cv) return;
  const yFmt = v => v >= 100 ? '$' + Math.round(v) : '$' + v.toFixed(2);
  const key = tf + ':' + (pts.length ? pts[pts.length - 1].t : 0) + ':' + (App.state ? App.state.stats.height : 0);
  const isLive = key !== lastPaintKey || pts.length < 2;
  lastPaintKey = key;
  priceChart(cv, pts, {
    height: 268, accent: '#7ca5cc', yFmt,
    live: pts.length ? { t: pts[pts.length - 1].t + 30, v: s.price } : null,
    onHover: () => {},
  });
}

function paintInputs() {
  const box = document.getElementById('mkt-inputs');
  if (!box) return;
  const a = activityInputs();
  box.innerHTML = `
    <div class="mkt-input-row"><span>Transactions on chain</span><b>${fmtNum(a.total_txs)}</b></div>
    <div class="mkt-input-row"><span>Block height</span><b>${fmtNum(a.height)}</b></div>
    <div class="mkt-input-row"><span>Circulating supply</span><b>${fmtNum(a.supply)}</b></div>
    <div class="mkt-input-row"><span>Network hashrate (est.)</span><b>${fmtNum(Math.round(a.hashrate))} H/s</b></div>
    <div class="mkt-input-row"><span>Mempool pressure</span><b>${a.mempool} waiting</b></div>
    <div class="mkt-input-row total"><span>Activity factor</span><b>×${a.factor.toFixed(3)}</b></div>`;
}

function pathRowHtml() {
  const s = pathSnapshot();
  const chgCls = s.chg24h >= 0 ? 'up' : 'down';
  return `
    <div class="mkt-row featured" data-nav-go="#/market" title="The native currency — see the chart above">
      <span class="mc-asset"><span class="coin-badge path">P</span>
        <span class="mc-names"><b>PATH</b><span class="mc-full">PATHchain</span></span></span>
      <span class="mc-price">${fmtUsd(s.price)}</span>
      <span class="mc-chg"><span class="chg-chip ${chgCls}">${fmtPct(s.chg24h)}</span></span>
      <span class="mc-spark"><canvas class="mc-spark-cv" height="34"></canvas></span>
      <span class="mc-mcap">${fmtCompact(s.mcap)}</span>
    </div>`;
}

function coinRowHtml(c) {
  const cls = c.chg24h >= 0 ? 'up' : 'down';
  const stateBadge = c.state === 'live' ? '' : ' <span class="tag-sys">CACHED</span>';
  return `
    <div class="mkt-row" title="${esc(c.name)} — price fetched from a public market API${c.state === 'live' ? '' : ' (last known value, this device is offline)'}">
      <span class="mc-asset"><span class="coin-badge">${esc(c.symbol.slice(0, 1))}</span>
        <span class="mc-names"><b>${esc(c.symbol)}</b><span class="mc-full">${esc(c.name)}${stateBadge}</span></span></span>
      <span class="mc-price">${fmtUsd(c.price)}</span>
      <span class="mc-chg"><span class="chg-chip ${cls}">${fmtPct(c.chg24h)}</span></span>
      <span class="mc-spark"><canvas data-spark="${esc(c.id)}" class="mc-spark-cv" height="34"></canvas></span>
      <span class="mc-mcap">${fmtCompact(c.mcap)}</span>
    </div>`;
}

export function destroy() {
  if (offTick) { offTick(); offTick = null; }
  if (offCoins) { offCoins(); offCoins = null; }
  if (offLive) { offLive(); offLive = null; }
  prevPrice = null;
}
